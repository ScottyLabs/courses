// Writes src/lib/api/schema.d.ts, the API's types, from its OpenAPI document (src/lib/api/openapi.json, which
// `cargo run -p courses-web-api -- openapi` regenerates). Several routes share an operationId (list, create, ...),
// which would declare the same member twice in the generated `operations`; each repeat is prefixed with its tag.
// Run with `deno task generate-api`.
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";

const SOURCE = new URL("../src/lib/api/openapi.json", import.meta.url);
const TARGET = new URL("../src/lib/api/schema.d.ts", import.meta.url);

type Operation = { operationId?: string; tags?: string[] };

// oxlint-disable-next-line typescript/no-unsafe-type-assertion -- the API writes this file from its own schema
const doc = JSON.parse(await readFile(SOURCE, "utf8")) as OpenAPI3;
const operations: Operation[] = Object.values(doc.paths ?? {}).flatMap((item) =>
  // oxlint-disable-next-line typescript/no-unsafe-type-assertion -- a path item maps methods to operations
  Object.values(item as Record<string, unknown>).filter(
    (v): v is Operation => typeof v === "object" && v !== null && "responses" in v,
  ),
);
const counts = new Map<string, number>();
for (const op of operations) {
  if (op.operationId !== undefined)
    counts.set(op.operationId, (counts.get(op.operationId) ?? 0) + 1);
}
for (const op of operations) {
  const id = op.operationId;
  if (id !== undefined && (counts.get(id) ?? 0) > 1)
    op.operationId = `${op.tags?.[0] ?? "api"}_${id}`;
}

const header =
  "/* oxlint-disable -- generated by `deno task generate-api` from openapi.json; do not edit */\n\n";
await writeFile(TARGET, header + astToString(await openapiTS(doc)));
console.log(`Wrote ${TARGET.pathname}`);
